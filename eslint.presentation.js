  //   - shadcn's button.tsx, badge.tsx and tabs.tsx export their `cva` variant
  //     builders next to the component. That is the CLI's output; you cannot
  //     fix it without editing generated code on every `shadcn add`.
  //   - ThemeProvider.tsx exports `useTheme` next to `ThemeProvider`, which is
  //     the standard React context pattern.
  //
  // Without this block `npx shadcn add button` produces code that fails lint
  // immediately. Scoped to these two folders only — everywhere else the rule
  // still applies.
