// ─── Class-discipline rules ────────────────────────────────────────────────
//
// These replace the hex ban from the antd/MUI/Carbon packs. In those libraries
// the theme was a JS object, so the failure mode was a hardcoded hex. Here the
// theme is a set of CSS custom properties consumed through Tailwind utility
// names, so the failure mode is a class that resolves to a colour the theme
// does not control. Same rule, different surface.
//
// Enforced as regexes over string literals rather than a Tailwind plugin: the
// published Tailwind ESLint plugins are v3-era and read a tailwind.config.js
// that no longer exists under v4.

// Arbitrary values that carry a COLOUR: bg-[#1677ff], border-[oklch(...)].
// NOT a general arbitrary-value ban — w-[340px] and max-h-[60vh] stay legal,
// because Tailwind's 4px scale cannot express every layout number and banning
// them produces worse workarounds than the problem. This one measured clean
// across the whole registry.
const ARBITRARY_COLOUR = "-\\[(?:#|rgb\\(|rgba\\(|hsl\\(|hsla\\(|oklch\\(|oklab\\(|color-mix\\()";

// Raw palette utilities: bg-blue-500, text-zinc-700, border-slate-200.
//
// THIS IS THE IMPORTANT ONE. It is what makes the Theme Showcase mean anything:
// change --primary and every screen moves — unless someone wrote bg-blue-600,
// in which case the showcase is lying. Also measured clean across the registry,
// so it is safe in both tiers.
const PALETTE_PREFIX =
  "(?:bg|text|border|ring|fill|stroke|shadow|from|via|to|divide|outline|decoration|accent|caret|placeholder)";
const PALETTE_HUE =
  "(?:slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose)";
const RAW_PALETTE = `\\b${PALETTE_PREFIX}-${PALETTE_HUE}-\\d{2,3}\\b`;

// Literal colours anywhere in a .tsx. AUTHORED ONLY — chart.tsx legitimately
// contains [&_.recharts-dot[stroke='#fff']], which is a selector targeting
// recharts' own DOM, not a theme bypass.
const LITERAL_COLOUR = "(?:#[0-9a-fA-F]{3,8}\\b|\\b(?:rgb|rgba|hsl|hsla|oklch|oklab|color-mix)\\()";

// bg-white / text-black. AUTHORED ONLY — the registry uses text-white in the
// destructive button and badge variants and bg-black/50 for the dialog and
// sheet scrims. Kept as ONE array entry so you can delete it in one line if
// your team decides overlay scrims are worth the exception.
const HARDCODED_BW = `\\b${PALETTE_PREFIX}-(?:white|black)\\b`;

/** Build a matching pair of selectors: plain strings and template chunks. */
const stringMatchers = (pattern, message) => [
  { selector: `Literal[value=/${pattern}/]`, message },
  { selector: `TemplateElement[value.raw=/${pattern}/]`, message },
];

// ─── Element ban (AUTHORED only) ───────────────────────────────────────────
//
// Much shorter than the antd list, and deliberately so. In July 2026 shadcn
// shipped typeset: one CSS file, <div className="typeset">, which styles raw
// headings, paragraphs, lists, tables and code. Writing <h1> IS the shadcn
// answer to typography. Banning it would fight the framework rather than
// enforce it, so headings, p, blockquote, code, ul/ol/li, a, img and form all
// stay legal — the logic bans above cover the behaviour half of <form>.
//
// What remains is the honest list: elements with a real component where a raw
// tag means someone rebuilt a themed control by hand.
const HAND_ROLLED = {
  button: "Use <Button>. It carries the variant, size and focus-ring tokens.",
  input: "Use <Input> / <Checkbox> / <Switch> / <RadioGroup> / <Slider> / <InputOTP>.",
  textarea: "Use <Textarea>.",
  select: "Use <Select>, or <NativeSelect> when you want the OS control.",
  label: "Use <Label>, or <Field> for a labelled control.",
  table: "Use <Table>. (Prose tables inside .typeset are the exception — see AGENTS.md §3.)",
  thead: "Use <TableHeader>.",
  tbody: "Use <TableBody>.",
  tfoot: "Use <TableFooter>.",
  tr: "Use <TableRow>.",
  td: "Use <TableCell>.",
  th: "Use <TableHead>.",
  hr: "Use <Separator>.",
  dialog: "Use <Dialog> / <AlertDialog> / <Sheet> / <Drawer>.",
  progress: "Use <Progress>.",
  kbd: "Use <Kbd>.",
};

// eslint-plugin-react already prefixes "<x> is forbidden," — don't repeat it
// here or every message reads "<button> is forbidden, <button> is forbidden."
const forbidElements = Object.entries(HAND_ROLLED).map(([element, message]) => ({
  element,
  message,
}));

